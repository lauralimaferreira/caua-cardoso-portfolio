import { createHash, randomBytes, scrypt, timingSafeEqual } from 'node:crypto';
import { promisify } from 'node:util';
const derive = promisify(scrypt);
const OPTIONS = { N: 32768, r: 8, p: 1, maxmem: 64 * 1024 * 1024 };
const FORMAT = /^scrypt\$32768\$8\$1\$([0-9a-f]{32})\$([0-9a-f]{64})$/;
export function validateHash(hash) { if (!FORMAT.test(hash || '')) throw new Error('ADMIN_PASSWORD_HASH must be generated by password:hash'); return hash; }
export async function hashPassword(password) {
  if (typeof password !== 'string' || password.length < 12 || Buffer.byteLength(password) > 256) throw new Error('Use a password of at least 12 characters and at most 256 UTF-8 bytes');
  const salt = randomBytes(16);
  const key = await derive(password, salt, 32, OPTIONS);
  return `scrypt$32768$8$1$${salt.toString('hex')}$${key.toString('hex')}`;
}
export async function verifyPassword(password, hash) {
  if (typeof password !== 'string' || Buffer.byteLength(password) > 256) return false;
  const [,salt,key] = FORMAT.exec(validateHash(hash));
  const actual = await derive(password, Buffer.from(salt,'hex'),32,OPTIONS);
  return timingSafeEqual(actual,Buffer.from(key,'hex'));
}
export const digest = value => createHash('sha256').update(value).digest('hex');
export function equalText(a,b) { return timingSafeEqual(Buffer.from(digest(a),'hex'),Buffer.from(digest(b),'hex')); }
export const newToken = () => randomBytes(32).toString('base64url');
export function readCookie(header, name) {
  const found = (header || '').split(';').map(x => x.trim()).filter(x => x.startsWith(name+'='));
  if (found.length !== 1) return null;
  const value = found[0].slice(name.length+1);
  return /^[A-Za-z0-9_-]{43}$/.test(value) ? value : null;
}
export function configFromEnv(env=process.env) {
  const dev = env.NODE_ENV === 'development';
  const url = new URL(env.APP_ORIGIN || 'invalid');
  if (url.origin !== env.APP_ORIGIN || url.username || url.password || (url.protocol !== 'https:' && !(dev && url.protocol==='http:' && ['localhost','127.0.0.1','[::1]'].includes(url.hostname)))) throw new Error('APP_ORIGIN must be the exact HTTPS origin (localhost HTTP only for development)');
  if (!env.DATABASE_URL) throw new Error('DATABASE_URL is required');
  const db = new URL(env.DATABASE_URL);
  if (!['postgres:','postgresql:'].includes(db.protocol)) throw new Error('DATABASE_URL must be PostgreSQL');
  const username = env.ADMIN_USERNAME || 'caua';
  if (!/^[A-Za-z0-9_-]{1,32}$/.test(username)) throw new Error('Invalid ADMIN_USERNAME');
  const passwordHash = validateHash(env.ADMIN_PASSWORD_HASH);
  const clientIpMode = env.AUTH_CLIENT_IP_MODE || (dev ? 'direct' : '');
  if (!['direct','railway-edge'].includes(clientIpMode) || (!dev && clientIpMode !== 'railway-edge')) throw new Error('AUTH_CLIENT_IP_MODE must be railway-edge in production (direct allowed in development)');
  const port = Number(env.PORT || 3000);
  if (!Number.isInteger(port) || port<1 || port>65535) throw new Error('Invalid PORT');
  const publicOrigin=env.PUBLIC_SITE_ORIGIN || 'https://caua-cardoso-portfolio.vercel.app';
  const publicUrl=new URL(publicOrigin);
  if(publicUrl.origin!==publicOrigin||publicUrl.username||publicUrl.password||(publicUrl.protocol!=='https:'&&!(dev&&publicUrl.protocol==='http:'&&['localhost','127.0.0.1','[::1]'].includes(publicUrl.hostname))))throw Error('PUBLIC_SITE_ORIGIN must be an exact HTTPS origin');
  return { publicOrigin, clientIpMode, origin:url.origin, secure:url.protocol==='https:', username,passwordHash,credentialVersion:digest(`${username}\0${passwordHash}`), dbUrl:env.DATABASE_URL,port,sessionSeconds:43200 };
}
